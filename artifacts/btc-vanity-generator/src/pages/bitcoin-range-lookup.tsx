import { useEffect, useState } from 'react';
import { AlertCircle, Search } from 'lucide-react';
import DonationAddress from '@/components/donation-address';
import { isValidMainnetBitcoinAddress } from '@/lib/bitcoin';
import { findGeneratedAddressRanges, type AddressRangeLookup } from '@/lib/range-lookup-index';
import './bitcoin-range-lookup.css';

export default function BitcoinRangeLookupPage({ active }: { active: boolean }) {
  const [address, setAddress] = useState('');
  const [matches, setMatches] = useState<AddressRangeLookup[] | null>(null);
  const [notice, setNotice] = useState('');
  const [noticeIsError, setNoticeIsError] = useState(false);

  useEffect(() => {
    if (active) document.title = 'Bitcoin Range Lookup | LUCKY BTC';
  }, [active]);

  function searchAddress() {
    setMatches(null);
    if (!isValidMainnetBitcoinAddress(address)) {
      setNotice('Enter a valid mainnet Bitcoin address.');
      setNoticeIsError(true);
      return;
    }

    const found = findGeneratedAddressRanges(address.trim());
    setMatches(found);
    setNotice(
      found.length > 0
        ? `${found.length.toLocaleString()} matching generated range${found.length === 1 ? '' : 's'} found in this browser tab.`
        : 'No match in the addresses generated in this browser tab. This lookup does not search all Bitcoin addresses.',
    );
    setNoticeIsError(false);
  }

  return (
    <main className="range-lookup-page" data-testid="page-bitcoin-range-lookup">
      <header className="range-lookup-intro">
        <div className="range-lookup-kicker"><Search aria-hidden="true" /> Local address lookup</div>
        <h1>Bitcoin Range Lookup</h1>
        <p>
          Paste an address generated by this app to find the key range that was
          searched. Lookup data stays in this browser tab.
        </p>
      </header>

      <section className="range-lookup-panel" aria-labelledby="range-lookup-title">
        <p className="range-lookup-label">ADDRESS SEARCH</p>
        <h2 id="range-lookup-title">Find a generated range</h2>
        <label className="range-lookup-field">
          <span>Bitcoin address</span>
          <input
            type="text"
            value={address}
            onChange={(event) => setAddress(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === 'Enter') searchAddress();
            }}
            placeholder="Paste a mainnet Bitcoin address"
            autoComplete="off"
            spellCheck={false}
            data-testid="input-range-lookup-address"
          />
        </label>
        <div className="range-lookup-controls">
          <span className="range-lookup-scope">
            Searches the latest 100,000 unique generated addresses in this tab.
          </span>
          <button
            className="range-lookup-search"
            type="button"
            onClick={searchAddress}
            data-testid="button-search-address-range"
          >
            <Search aria-hidden="true" /> Search
          </button>
        </div>
        <p className="range-lookup-format">
          An address does not reveal its private key range. Only ranges recorded
          when this app generates addresses can be found here; no keys are
          brute-forced or sent to a service.
        </p>
        {notice && (
          <p
            className={`range-lookup-notice${noticeIsError ? ' is-error' : ''}`}
            role={noticeIsError ? 'alert' : 'status'}
            data-testid="status-range-lookup"
          >
            {noticeIsError && <AlertCircle aria-hidden="true" />}
            {notice}
          </p>
        )}
      </section>

      {matches && (
        <section className="range-lookup-results" aria-labelledby="range-lookup-results-title">
          <div className="range-lookup-results-heading">
            <div>
              <p className="range-lookup-label">LOOKUP RESULTS</p>
              <h2 id="range-lookup-results-title">Matching ranges</h2>
            </div>
            <span>{matches.length} found</span>
          </div>
          {matches.length > 0 ? (
            <div className="range-lookup-table-wrap">
              <table className="range-lookup-table">
                <thead>
                  <tr>
                    <th scope="col">Address</th>
                    <th scope="col">Range start (hex)</th>
                    <th scope="col">Range end (hex)</th>
                  </tr>
                </thead>
                <tbody>
                  {matches.map((match, index) => (
                    <tr key={`${match.address}-${match.startHex}-${match.endHex}-${index}`}>
                      <td><code>{match.address}</code></td>
                      <td><code>{match.startHex}</code></td>
                      <td><code>{match.endHex}</code></td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          ) : (
            <p className="range-lookup-empty">This address was not generated in the current browser tab.</p>
          )}
        </section>
      )}
      <footer className="donation-page-footer">
        <DonationAddress />
      </footer>
    </main>
  );
}
